CREATE OR REPLACE TRIGGER trg_validar_fecha_inicio
BEFORE INSERT OR UPDATE ON INTERNACION
FOR EACH ROW
BEGIN
    -- Comparamos la fecha ingresada con la fecha actual del sistema (SYSDATE)
    IF :NEW.fecha_inicio > SYSDATE THEN
        RAISE_APPLICATION_ERROR(-20009, 'Error de validación: La fecha de inicio de la internación no puede ser mayor a la fecha actual.');
    END IF;
END;
/
CREATE OR REPLACE TRIGGER trg_posee_fecha
BEFORE INSERT OR UPDATE ON POSEE
FOR EACH ROW
DECLARE
    v_inicio DATE;
    v_fin DATE;
BEGIN
    SELECT fecha_inicio, fecha_fin INTO v_inicio, v_fin
    FROM INTERNACION
    WHERE ID_INTERNACION = :NEW.ID_INTERNACION;

    IF CAST(:NEW.fechaHora AS DATE) < v_inicio THEN
        RAISE_APPLICATION_ERROR(-20001,'La asignación de cama no puede ser anterior al inicio de la internación.');
    END IF;

    IF v_fin IS NOT NULL AND CAST(:NEW.fechaHora AS DATE) > v_fin THEN
        RAISE_APPLICATION_ERROR(-20002,'La asignación de cama no puede ser posterior al fin de la internación.');
    END IF;
END;
/

