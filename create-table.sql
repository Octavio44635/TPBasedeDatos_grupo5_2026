    VALUES (p_piso, UPPER(p_orientacion), p_id_sector)
    RETURNING id_habitacion INTO p_id_habitacion;

    v_semana(1).dia := 'LUNES';     v_semana(1).turno := p_turno_lun;
    v_semana(2).dia := 'MARTES';    v_semana(2).turno := p_turno_mar;
