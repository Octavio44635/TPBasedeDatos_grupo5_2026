    v_semana(7).dia := 'DOMINGO';   v_semana(7).turno := p_turno_dom;

    FOR i IN 1..7 LOOP
        BEGIN
            SELECT id_ronda INTO v_id_ronda
            FROM RONDA
            WHERE dia_semana = v_semana(i).dia
